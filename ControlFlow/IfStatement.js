// what is if Statement
// if statement is a conditional statement that executes a block of code if the condition is true
//iska kaam hota hai code ko tabhi chalana jab koi condition true ho.

//Basic Syntax:
if (condition) {
    // code yahan chalega agar condition true ho
  }

  // Example:
  let age = 20;

if (age >= 18) {
  console.log("You are an adult!");
}

// if...else:
let isRaining = true;

if (isRaining) {
  console.log("Take an umbrella!");
} else {
  console.log("Enjoy the sunshine!");
}

// if...else if...else:
let score = 85;

if (score >= 90) {
  console.log("Grade A");
} else if (score >= 80) {
  console.log("Grade B");
} else {
  console.log("Keep trying!");
}
